export function enrichChecklistDefinition<T extends PlaybookStepDef['checklist'][number]>(item: T): T {
  const prompt = CHECKLIST_RESPONSE_PROMPTS[item.id]
  if (!prompt || item.responseRequired !== undefined) return item
  return { ...item, responseRequired: true, responsePrompt: item.responsePrompt || prompt }
}

export function enrichProjectChecklistItem(item: ProjectChecklistItem): ProjectChecklistItem {
  const prompt = CHECKLIST_RESPONSE_PROMPTS[item.id]
  return {
    ...item,
    responseRequired: item.responseRequired ?? Boolean(prompt),
    responsePrompt: item.responsePrompt || prompt,
    response: item.response ?? ''
  }
}
